#!/bin/bash
# Regenerates <overlay>/flows/kustomization.yaml from the *.json files in <overlay>/flows/.
#
#   tools/sync-flows.sh overlays/black
#
# Each flow file becomes its OWN ConfigMap (flow-<name>), and all of them are projected into /flows
# in the Job. Run this after adding, renaming or removing a flow file, then commit the result.
set -euo pipefail

OVERLAY="${1:?usage: tools/sync-flows.sh overlays/<env>}"
DIR="$OVERLAY/flows"
OUT="$DIR/kustomization.yaml"
LIMIT=1000000   # ConfigMaps are capped at 1 MiB (1048576 bytes) including metadata — leave headroom

[ -d "$DIR" ] || { echo "No such folder: $DIR" >&2; exit 1; }

shopt -s nullglob
files=("$DIR"/*.json)
[ ${#files[@]} -gt 0 ] || { echo "No *.json files in $DIR" >&2; exit 1; }

gen=""
src=""
seen=" "
for f in "${files[@]}"; do
  base=$(basename "$f")
  if ! [[ "$base" =~ ^[-._a-zA-Z0-9]+$ ]]; then
    echo "ERROR: '$base' — file names may only contain letters, digits, '-', '_' and '.' (ConfigMap key rules)" >&2
    exit 1
  fi
  size=$(wc -c < "$f")
  if [ "$size" -gt "$LIMIT" ]; then
    echo "ERROR: $base is $size bytes — too big for a ConfigMap (max ~1 MiB). Bake it into the image instead." >&2
    exit 1
  fi
  if command -v jq >/dev/null && ! jq empty "$f" 2>/dev/null; then
    echo "ERROR: $base is not valid JSON" >&2
    exit 1
  fi
  # ConfigMap name: flow-<file name without .json>, lower-case, DNS-1123 safe
  name="flow-$(echo "${base%.json}" | tr '[:upper:]' '[:lower:]' | sed -E 's/[^a-z0-9.-]+/-/g; s/^[.-]+//; s/[.-]+$//')"
  name="${name:0:240}"
  if [[ "$seen" == *" $name "* ]]; then
    echo "ERROR: two files map to the same ConfigMap name '$name' — rename one" >&2
    exit 1
  fi
  seen="$seen$name "

  gen+="  - name: $name
    files:
      - $base
"
  src+="                    - configMap:
                        name: $name
"
  printf '  %-60s %8s bytes\n' "$base -> $name" "$size"
done

cat > "$OUT" <<EOF
# GENERATED by tools/sync-flows.sh — do not edit by hand. Re-run it after changing the flow files.
apiVersion: kustomize.config.k8s.io/v1alpha1
kind: Component

# One ConfigMap per flow file (content-hashed name, so a changed flow gives a new ConfigMap).
configMapGenerator:
$gen
# Project every flow ConfigMap into /flows in the Job.
patches:
  - target:
      kind: Job
      name: nifi-deploy
    patch: |-
      apiVersion: batch/v1
      kind: Job
      metadata:
        name: nifi-deploy
      spec:
        template:
          spec:
            volumes:
              - name: flows
                projected:
                  sources:
$src
EOF

echo "Wrote $OUT (${#files[@]} flow ConfigMaps)"
