#!/bin/bash
# Regenerates <env-dir>/flows/kustomization.yaml from the *.json files in <env-dir>/flows/.
#
#   flow-deployer/tools/sync-flows.sh flow-deployer/env/sil-direct/red
#
# Each flow file becomes its OWN ConfigMap, named after the flow WITHOUT the version suffix:
#   Circuit-Manager-version-1.json  ->  flow-deploy-flow-circuit-manager
#   (the overlay's namePrefix makes it nifi-red-flow-deploy-flow-circuit-manager)
# so moving to version-2 only swaps the file. All flow ConfigMaps are projected into /flows.
set -euo pipefail

ENV_DIR="${1:?usage: tools/sync-flows.sh flow-deployer/env/<env>/<side>}"
DIR="$ENV_DIR/flows"
OUT="$DIR/kustomization.yaml"
LIMIT=1000000   # ConfigMaps are capped at 1 MiB (1048576 bytes) including metadata — leave headroom

[ -d "$DIR" ] || { echo "No such folder: $DIR" >&2; exit 1; }

shopt -s nullglob
files=("$DIR"/*.json)
[ ${#files[@]} -gt 0 ] || { echo "No *.json files in $DIR" >&2; exit 1; }

gen=""
src=""
seen=" "
for f in "${files[@]}"; do
  base=$(basename "$f")
  if ! [[ "$base" =~ ^[-._a-zA-Z0-9]+$ ]]; then
    echo "ERROR: '$base' — file names may only contain letters, digits, '-', '_' and '.' (ConfigMap key rules)" >&2
    exit 1
  fi
  size=$(wc -c < "$f")
  if [ "$size" -gt "$LIMIT" ]; then
    echo "ERROR: $base is $size bytes — too big for a ConfigMap (max ~1 MiB)" >&2
    exit 1
  fi
  if command -v jq >/dev/null && ! jq empty "$f" 2>/dev/null; then
    echo "ERROR: $base is not valid JSON" >&2
    exit 1
  fi
  # flow name without version suffix: "-version-1", "_version_2", "-v3"
  stem=$(echo "${base%.json}" | sed -E 's/[-_]?(version|v)[-_]?[0-9]+$//I')
  name="flow-deploy-flow-$(echo "$stem" | tr '[:upper:]' '[:lower:]' | sed -E 's/[^a-z0-9.-]+/-/g; s/^[.-]+//; s/[.-]+$//')"
  name="${name:0:230}"
  if [[ "$seen" == *" $name "* ]]; then
    echo "ERROR: two files map to '$name' (two versions of the same flow?) — keep only one" >&2
    exit 1
  fi
  seen="$seen$name "

  gen+="  - name: $name
    files:
      - $base
"
  src+="                    - configMap:
                        name: $name
"
  printf '  %-55s -> %-50s %8s bytes\n' "$base" "$name" "$size"
done

cat > "$OUT" <<EOF
# GENERATED by flow-deployer/tools/sync-flows.sh — do not edit by hand. Re-run it after changing flow files.
apiVersion: kustomize.config.k8s.io/v1alpha1
kind: Component

# One ConfigMap per flow file.
configMapGenerator:
$gen
generatorOptions:
  disableNameSuffixHash: true

# Project every flow ConfigMap into /flows in the deployer Job.
patches:
  - target:
      kind: Job
      name: flow-deploy-job
    patch: |-
      apiVersion: batch/v1
      kind: Job
      metadata:
        name: flow-deploy-job
      spec:
        template:
          spec:
            volumes:
              - name: flows
                projected:
                  sources:
$src
EOF

echo "Wrote $OUT (${#files[@]} flow ConfigMaps)"
